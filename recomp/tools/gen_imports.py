"""Generate runtime/imports.gen.cpp: one __imp__ function per XEX import, forwarding
to the runtime's import dispatcher.

Usage: gen_imports.py <ppc_recomp_shared.h> <imports.gen.cpp>"""
import re
import sys

names = sorted(set(
    m.group(1) for m in re.finditer(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", open(sys.argv[1], encoding="utf-8").read())
    if not m.group(1).startswith("sub_")))

with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by tools/gen_imports.py. Do not edit.\n")
    out.write('#include "guest.h"\n\n')
    out.write("const char* const g_importNames[] =\n{\n")
    for name in names:
        out.write('    "%s",\n' % name)
    out.write("};\n\n")
    out.write("const size_t g_importCount = %d;\n" % len(names))
    out.write("ImportHandler g_importHandlers[%d];\n\n" % len(names))
    for index, name in enumerate(names):
        out.write("PPC_FUNC(__imp__%s) { ImportDispatch(%d, ctx, base); }\n" % (name, index))

print("%d imports" % len(names))
